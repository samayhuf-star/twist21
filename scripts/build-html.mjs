// Turns game/index.html into src/gameHtml.ts so the WebView needs no file access.
import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(new URL('../game/index.html', import.meta.url), 'utf8');
writeFileSync(new URL('../src/gameHtml.ts', import.meta.url), `// Generated by scripts/build-html.mjs. Do not edit.\nconst gameHtml: string = ${JSON.stringify(html)};\nexport default gameHtml;\n`);
console.log('src/gameHtml.ts written,', html.length, 'chars');
